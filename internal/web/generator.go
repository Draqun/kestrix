package web

import (
	"fmt"
	"strings"

	"gitlab.com/lunaris-bot/metaci/internal/dag"
	"gitlab.com/lunaris-bot/metaci/internal/model"
)

// GenerateGitLabCI produces a .gitlab-ci.yml string from the resolved DAG nodes.
//
// The generated YAML is minimal but functional: each triggered task becomes a
// job. Dependencies are mapped to GitLab's "needs" keyword. Manual tasks get
// "when: manual". Container images are set per-job (the per-job dynamic image
// pulling concept).
func GenerateGitLabCI(proj model.Project, nodes []dag.Node) string {
	var sb strings.Builder

	// Header comment.
	sb.WriteString("# Auto-generated by Kestrix — do not edit manually\n")
	sb.WriteString(fmt.Sprintf("# Project: %s\n\n", proj.Name))

	// Stages: derive from the dependency order.
	// Simple approach: all jobs start in "build" unless they depend on something,
	// then they go to "test", and if they depend on test jobs, "deploy".
	stages := deriveStages(nodes)
	if len(stages) > 0 {
		sb.WriteString("stages:\n")
		for _, s := range stages {
			sb.WriteString(fmt.Sprintf("  - %s\n", s))
		}
		sb.WriteString("\n")
	}

	// Default image (from project-level setting).
	if proj.DefaultImage != "" {
		sb.WriteString(fmt.Sprintf("default:\n  image: %s\n\n", proj.DefaultImage))
	}

	// Jobs.
	for _, node := range nodes {
		job := node.Task
		stage := assignStage(job, nodes)

		sb.WriteString(fmt.Sprintf("%s:\n", job.Name))
		sb.WriteString(fmt.Sprintf("  stage: %s\n", stage))

		// Image: per-job override or project default.
		if job.Execute.Image != "" {
			sb.WriteString(fmt.Sprintf("  image: %s\n", job.Execute.Image))
		}

		// Dependencies.
		if len(job.DependsOn) > 0 {
			sb.WriteString("  needs:\n")
			for _, dep := range job.DependsOn {
				sb.WriteString(fmt.Sprintf("    - %s\n", dep))
			}
		}

		// Manual approval gate.
		if job.Manual {
			sb.WriteString("  when: manual\n")
		}

		// Script: clone the repo and run the script.
		sb.WriteString("  script:\n")
		sb.WriteString(fmt.Sprintf("    - echo \"Running %s in repo %s\"\n", job.Name, job.Execute.Repo))
		sb.WriteString(fmt.Sprintf("    - %s\n", job.Execute.Script))

		sb.WriteString("\n")
	}

	return sb.String()
}

// deriveStages computes the pipeline stages from the node dependency graph.
// deriveStages determines which stages the pipeline needs based on
// the dependency graph. Tasks with no deps → "build", tasks with deps
// that depend on build tasks → "test", manual tasks → "deploy".
func deriveStages(nodes []dag.Node) []string {
	hasBuild := false
	hasTest := false
	hasDeploy := false

	// First pass: identify which stages are needed.
	for _, n := range nodes {
		if len(n.Task.DependsOn) == 0 && !n.Task.Manual {
			hasBuild = true
		}
		if len(n.Task.DependsOn) > 0 && !n.Task.Manual {
			hasTest = true
		}
		if n.Task.Manual {
			hasDeploy = true
		}
	}

	var stages []string
	if hasBuild {
		stages = append(stages, "build")
	}
	if hasTest {
		stages = append(stages, "test")
	}
	if hasDeploy {
		stages = append(stages, "deploy")
	}
	if len(stages) == 0 {
		stages = append(stages, "build")
	}
	return stages
}

// assignStage determines which stage a task belongs to.
func assignStage(task model.Task, nodes []dag.Node) string {
	if task.Manual {
		return "deploy"
	}
	// If the task has dependencies, it's at least "test" level.
	if len(task.DependsOn) > 0 {
		for _, dep := range task.DependsOn {
			if strings.Contains(dep, "test") {
				return "deploy"
			}
		}
		return "test"
	}
	return "build"
}
